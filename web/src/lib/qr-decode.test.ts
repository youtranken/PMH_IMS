/** Vẽ ma trận QR thành điểm ảnh RGBA như ảnh chụp màn hình: mỗi ô `scale` px, viền trắng 4 ô. */
function render(rows: string[], scale = 4, quiet = 4, invert = false) {
  const size = (rows.length + quiet * 2) * scale;
  const data = new Uint8ClampedArray(size * size * 4);
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const my = Math.floor(y / scale) - quiet;
      const mx = Math.floor(x / scale) - quiet;
      const dark = rows[my]?.[mx] === '#';
      const v = dark !== invert ? 0 : 255;
      const i = (y * size + x) * 4;
      data[i] = v;
      data[i + 1] = v;
      data[i + 2] = v;
      data[i + 3] = 255;
    }
  }
  return { data, width: size, height: size };
}

describe('decodeQrPixels — đọc ảnh QR ngay trên trình duyệt (Q-18)', () => {
  it('đọc ra đúng chuỗi otpauth từ ảnh QR', () => {
    const image = render(QR_FIXTURE_ROWS);
    expect(decodeQrPixels(image.data, image.width, image.height)).toBe(QR_FIXTURE_TEXT);
  });

  it('QR in ngược màu (theme tối) vẫn đọc được', () => {
    const image = render(QR_FIXTURE_ROWS, 4, 4, true);
    expect(decodeQrPixels(image.data, image.width, image.height)).toBe(QR_FIXTURE_TEXT);
  });

  it('ảnh không có QR → null, không ném', () => {
    const blank = new Uint8ClampedArray(64 * 64 * 4).fill(255);
    expect(decodeQrPixels(blank, 64, 64)).toBeNull();
  });
});
